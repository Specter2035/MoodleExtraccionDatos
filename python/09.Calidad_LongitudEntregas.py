import random

def generar_rubrica_por_alumno(grade, df_rubric):
    resultados = {}

    for _, row in df_rubric.iterrows():
        max_score = row["puntaje_max"]

        porcentaje = grade / 100
        score = round(max_score * porcentaje)

        # Variación realista
        score = max(0, min(max_score, score + random.randint(-2, 2)))

        resultados[row["criterio"]] = score

    return resultados

rows = []

for _, alumno in df_grades.iterrows():
    rubrica_scores = generar_rubrica_por_alumno(alumno["grade"], df_rubric)

    fila = {
        "userid": alumno["userid"],
        "nombre": alumno["fullname"],
        "grade": alumno["grade"]
    }

    fila.update(rubrica_scores)

    rows.append(fila)

df_final = pd.DataFrame(rows)
