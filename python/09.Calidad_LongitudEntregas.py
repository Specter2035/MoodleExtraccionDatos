def limpiar_texto(texto):
    if not texto:
        return ""
    texto = re.sub(r"<.*?>", "", texto)
    texto = texto.replace("\r\n", " ").replace("\n", " ")
    return " ".join(texto.split())


def rubrics_summary(rubrics_json):
    rows = []

    if isinstance(rubrics_json, dict):
        rubrics_json = [rubrics_json]

    for item in rubrics_json:
        rubric_data = item.get("rubric", {})

        for area in rubric_data.get("areas", []):
            for definition in area.get("definitions", []):
                rubric_def = definition.get("rubric", {})

                # Diccionario para mapear evaluaciones por criterio
                evals = {ev.get("criterionid"): ev.get("score") for ev in rubric_def.get("evaluations", [])}

                for crit in rubric_def.get("rubric_criteria", []):
                    crit_id = crit.get("id")
                    criterio = limpiar_texto(crit.get("description"))

                    max_score = max([lvl.get("score", 0) for lvl in crit.get("levels", [])]) if crit.get("levels") else 0
                    puntaje_docente = evals.get(crit_id)

                    rows.append({
                        "criterio": criterio,
                        "puntaje_max": max_score,
                        "puntaje_docente": puntaje_docente
                    })

    return pd.DataFrame(rows)


